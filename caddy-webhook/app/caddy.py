"""Deploy infra-caddy: GitHub push webhook -> fast-forward the checkout ->
`caddy reload`.

The webhook is only a nudge. Which commit to deploy comes from fetching the
configured branch, never from the payload, so a replayed or forged delivery
can't pick an old or foreign commit. Only fast-forwards are deployed: a
force-pushed or rewritten branch is refused and reported. If Caddy rejects
the new config, the checkout is put back, so a later Caddy restart doesn't
load the config that failed.
"""

from __future__ import annotations

import os
import shlex
import threading
from collections.abc import Callable
from dataclasses import dataclass

import git
import logfire
from discord_webhook import DiscordEmbed

from app import notify
from app.settings import CaddySettings, NotifySettings

_lock = threading.Lock()

Reloader = Callable[[], None]


class Refused(Exception):
    """The branch can't be deployed as it stands (e.g. history was rewritten)."""


class ReloadFailed(Exception):
    pass


@dataclass(frozen=True)
class Outcome:
    prev_commit: str
    new_commit: str

    @property
    def changed(self) -> bool:
        return self.prev_commit != self.new_commit


def should_deploy(event: str | None, payload: dict, settings: CaddySettings) -> str | None:
    """None if this push should deploy, else why it's ignored."""
    if event != "push":
        return f"not a push event ({event})"
    repo = (payload.get("repository") or {}).get("full_name")
    if repo != settings.repo:
        return f"not {settings.repo} ({repo})"
    if payload.get("ref") != f"refs/heads/{settings.branch}":
        return f"not {settings.branch} ({payload.get('ref')})"
    return None


def version_snippet_path(settings: CaddySettings) -> str:
    return os.path.join(settings.repo_path, "snippets", "generated", "config_version.caddy")


def write_version_snippet(settings: CaddySettings, commit: git.Commit) -> None:
    """Write the snippet the Caddyfile imports to serve its own version.

    Caddy bakes it in when it adapts the Caddyfile, so the running config reports
    the commit it was loaded from - a failed reload keeps reporting the old one.
    """
    # Braces would be read as runtime placeholders by `respond`
    subject = commit.message.splitlines()[0] if commit.message else ""
    subject = subject.replace("{", "(").replace("}", ")")
    subject = subject.replace("\\", "\\\\").replace('"', '\\"')

    snippet = f"""# Generated by caddy-webhook; do not edit.
header Content-Type "text/plain; version=0.0.4; charset=utf-8"
respond <<EOF
	# HELP caddy_config_info Caddyfile commit loaded into Caddy's running config.
	# TYPE caddy_config_info gauge
	caddy_config_info{{commit="{commit.hexsha}",commit_short="{commit.hexsha[:7]}",subject="{subject}"}} 1
	# HELP caddy_config_commit_timestamp_seconds Commit time of the Caddyfile loaded into Caddy's running config.
	# TYPE caddy_config_commit_timestamp_seconds gauge
	caddy_config_commit_timestamp_seconds {commit.committed_date}

	EOF 200
"""
    path = version_snippet_path(settings)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(snippet)


def docker_reloader(settings: CaddySettings) -> Reloader:
    def reload() -> None:
        import docker

        container = docker.from_env().containers.get(settings.container_name)
        exit_code, output = container.exec_run(
            ["/config/caddy", "reload", "-c", "/config/Caddyfile"], workdir="/config"
        )
        if exit_code != 0:
            raise ReloadFailed(
                f"caddy reload exited with code {exit_code}:\n{output.decode(errors='replace')}"
            )

    return reload


def _git_env(settings: CaddySettings) -> dict[str, str]:
    env = {"GIT_TERMINAL_PROMPT": "0"}
    if settings.ssh_key_file:
        parts = [
            "ssh",
            "-i", settings.ssh_key_file,
            "-o", "IdentitiesOnly=yes",
            "-o", "BatchMode=yes",
            "-o", "StrictHostKeyChecking=yes",
        ]
        if settings.ssh_known_hosts_file:
            parts += ["-o", f"UserKnownHostsFile={settings.ssh_known_hosts_file}"]
        env["GIT_SSH_COMMAND"] = shlex.join(parts)
    return env


def _remote(repo: git.Repo, settings: CaddySettings) -> git.Remote:
    names = [r.name for r in repo.remotes]
    # Older checkouts named the remote after the branch
    return repo.remotes[settings.branch] if settings.branch in names else repo.remotes.origin


def deploy(settings: CaddySettings, reload: Reloader) -> Outcome:
    """Fast-forward the checkout to the branch's head and reload Caddy."""
    with _lock:
        repo = git.Repo(settings.repo_path)
        prev = repo.head.commit
        remote = _remote(repo, settings)
        tracking = f"refs/remotes/{remote.name}/{settings.branch}"
        with repo.git.custom_environment(**_git_env(settings)):
            logfire.info("Fetching {branch}", branch=settings.branch)
            remote.fetch(f"+refs/heads/{settings.branch}:{tracking}")
        new = repo.commit(tracking)

        if new == prev:
            return Outcome(prev.hexsha, new.hexsha)
        if not repo.is_ancestor(prev, new):
            raise Refused(
                f"{settings.branch} is now {new.hexsha[:7]}, which doesn't descend from the "
                f"deployed {prev.hexsha[:7]}: history was rewritten or the checkout has local "
                "commits. Not deploying; fix the checkout by hand."
            )

        repo.git.merge("--ff-only", new.hexsha)
        write_version_snippet(settings, new)
        try:
            reload()
        except Exception as e:
            # Caddy keeps running the old config; put the checkout back to match it
            repo.git.reset("--hard", prev.hexsha)
            write_version_snippet(settings, prev)
            raise ReloadFailed(f"{e}\n\nRolled the checkout back to {prev.hexsha[:7]}.") from e
        return Outcome(prev.hexsha, new.hexsha)


def notify_success(outcome: Outcome, settings: CaddySettings, notify_settings: NotifySettings) -> None:
    if not outcome.changed:
        return
    repo = git.Repo(settings.repo_path)
    prev, new = repo.commit(outcome.prev_commit), repo.commit(outcome.new_commit)
    changes = []
    for d in prev.diff(new):
        changes.append(d.a_path if d.a_path == d.b_path else f"{d.a_path} ==> {d.b_path}")
    commits = list(repo.iter_commits(f"{prev.hexsha}..{new.hexsha}"))
    url = f"https://github.com/{settings.repo}"

    description = f"{len(changes)} files changed\n" + "\n".join(f"- `{c}`" for c in changes)
    embed = DiscordEmbed(title="Caddy repo updated", description=description[:3500], color=notify.GREEN)
    embed.add_embed_field(
        name=f"Now ({len(commits)} new commit{'s' if len(commits) != 1 else ''})",
        value=f"{new.summary} - [{new.hexsha[:7]}]({url}/commit/{new.hexsha})",
        inline=False,
    )
    embed.add_embed_field(
        name="Was",
        value=f"{prev.summary} - [{prev.hexsha[:7]}]({url}/commit/{prev.hexsha})",
        inline=False,
    )
    notify.discord(notify_settings, embed)
